import { useCallback, useEffect, useRef, useState } from 'react';
import { toApiError, type ApiError } from '../api/client';
import { generateRecommendation, getLatestRecommendation } from '../api/recommendationsApi';
import type { DashboardPeriod, RecommendationView } from '../api/types';
import { DEVICE_ID } from '../config/appConfig';

export interface RecommendationsState {
  data: RecommendationView | null;
  error: ApiError | null;
  /** Initial retrieval of the stored recommendation. */
  loading: boolean;
  /** A generate request is in flight. */
  generating: boolean;
  /** Explains the outcome of the last generation (fresh vs cached). */
  notice: string | null;
  lastUpdatedAt: number | null;
  reloadLatest: () => Promise<void>;
  generate: (refresh?: boolean) => Promise<void>;
}

/**
 * AI recommendations for a period.
 *
 * - the stored recommendation is fetched once per period (`GET .../latest`)
 * - Gemini is only invoked from an explicit user action (`POST`), and `refresh`
 *   is only forwarded when the user asks for a brand new analysis
 * - `RECOMMENDATION_NOT_FOUND` is a normal empty state, not an error
 */
export function useRecommendations(period: DashboardPeriod): RecommendationsState {
  const [data, setData] = useState<RecommendationView | null>(null);
  const [error, setError] = useState<ApiError | null>(null);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [notice, setNotice] = useState<string | null>(null);
  const [lastUpdatedAt, setLastUpdatedAt] = useState<number | null>(null);

  const mountedRef = useRef(true);
  const abortRef = useRef<AbortController | null>(null);
  const epochRef = useRef(0);

  const reloadLatest = useCallback(async (): Promise<void> => {
    const epoch = ++epochRef.current;
    abortRef.current?.abort();
    const controller = new AbortController();
    abortRef.current = controller;

    setLoading(true);
    try {
      const result = await getLatestRecommendation(period, DEVICE_ID, controller.signal);
      if (!mountedRef.current || epoch !== epochRef.current) return;
      setData(result);
      setError(null);
      setNotice(null);
      setLastUpdatedAt(Date.now());
    } catch (caught) {
      if (!mountedRef.current || epoch !== epochRef.current) return;
      const apiError = toApiError(caught);
      if (apiError.code === 'CANCELLED') return;
      if (apiError.code === 'RECOMMENDATION_NOT_FOUND') {
        // Nothing stored yet — an empty state, not a failure.
        setData(null);
        setError(null);
      } else {
        setError(apiError);
      }
    } finally {
      if (mountedRef.current && epoch === epochRef.current) setLoading(false);
    }
  }, [period]);

  const generate = useCallback(
    async (refresh = false): Promise<void> => {
      const epoch = ++epochRef.current;
      abortRef.current?.abort();
      const controller = new AbortController();
      abortRef.current = controller;

      setGenerating(true);
      setNotice(null);
      try {
        const result = await generateRecommendation(period, {
          refresh,
          deviceId: DEVICE_ID,
          signal: controller.signal,
        });
        if (!mountedRef.current || epoch !== epochRef.current) return;
        setData(result);
        setError(null);
        setLastUpdatedAt(Date.now());
        setNotice(
          result.status === 'success'
            ? result.cached
              ? 'Served from the backend cache: Gemini was not called again for this statistics snapshot.'
              : 'Fresh analysis generated by Gemini from the aggregated statistics.'
            : result.cached
              ? 'The backend returned its cached entry for this period, and it is not a successful analysis.'
              : 'The backend attempted an analysis but did not produce a successful result.',
        );
      } catch (caught) {
        if (!mountedRef.current || epoch !== epochRef.current) return;
        const apiError = toApiError(caught);
        if (apiError.code === 'CANCELLED') return;
        setError(apiError);
      } finally {
        if (mountedRef.current && epoch === epochRef.current) {
          setGenerating(false);
          setLoading(false);
        }
      }
    },
    [period],
  );

  useEffect(() => {
    mountedRef.current = true;
    void reloadLatest();
    return () => {
      mountedRef.current = false;
      epochRef.current += 1;
      abortRef.current?.abort();
    };
  }, [reloadLatest]);

  return {
    data,
    error,
    loading,
    generating,
    notice,
    lastUpdatedAt,
    reloadLatest,
    generate,
  };
}
